#!/usr/bin/env python
"""R5: pilot_v0 (learned SDF) vs pilot_v1 (exact union SDF) analysis, plus the per-state replay on v1.

Reads only logged labels (data/labels/pilot_v{0,1}/) and writes reports/run02/analysis_v1.md + figures.
All numbers come from logged CMG-RRT queries; nothing is simulated.
"""
import argparse
import json
import os
import subprocess
import sys
from collections import Counter, defaultdict

import numpy as np

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))


def load(d):
    labs = [json.loads(l) for l in open(os.path.join(d, "labels.jsonl"))]
    summ = {}
    for l in open(os.path.join(d, "summary.jsonl")):
        r = json.loads(l)
        summ[r["assembly_id"]] = r          # last line wins
    return labs, summ


def pct(x, qs=(10, 50, 90)):
    return [round(float(np.percentile(x, q)), 3) for q in qs] if len(x) else None


def stats(labs):
    n = len(labs)
    succ = [r for r in labs if r["outcome"] == "success"]
    uns = [r for r in labs if r["outcome"] != "success"]
    inv = [r for r in uns if r.get("start_valid") is False]
    return {"queries": n, "success": len(succ), "success_rate": len(succ) / n if n else None,
            "unsolved": len(uns), "unsolved_start_invalid": len(inv),
            "start_invalid_share_of_unsolved": len(inv) / len(uns) if uns else None,
            "start_valid_rate_all": float(np.mean([bool(r.get("start_valid")) for r in labs])) if n else None,
            "errors": sum(1 for r in labs if r.get("error")),
            "success_time_p10_p50_p90": pct([r["time_s"] for r in succ]),
            "success_iter_p50_p90_max": ([int(np.percentile([r["iterations"] for r in succ], q)) for q in (50, 90)]
                                         + [max(r["iterations"] for r in succ)]) if succ else None,
            "planner_s_total": float(sum(r["time_s"] or 0 for r in labs)),
            "prep_s_p50_p90": pct([r.get("prep_s") or 0 for r in labs], (50, 90)),
            "setup_time_s_p50_p90": pct([r["setup_time_s"] for r in labs if r.get("setup_time_s") is not None], (50, 90))}


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--v0", default=os.path.join(ROOT, "data/labels/pilot_v0"))
    ap.add_argument("--v1", default=os.path.join(ROOT, "data/labels/pilot_v1"))
    ap.add_argument("--out", default=os.path.join(ROOT, "reports/run02/analysis_v1.md"))
    ap.add_argument("--fig-dir", default=os.path.join(ROOT, "reports/run02/figures"))
    ap.add_argument("--label-log", default=os.path.join(ROOT, "experiments/2026-11-22_pilot_v1_labels/stdout.log"))
    ap.add_argument("--rot-deg", type=float, default=15.0)
    args = ap.parse_args()
    os.makedirs(args.fig_dir, exist_ok=True)
    v0, s0 = load(args.v0)
    v1, s1 = load(args.v1)
    L = ["# R5 analysis: pilot_v0 (learned SDF) vs pilot_v1 (exact union SDF, eps 0.005)\n",
         f"Sources: `{os.path.relpath(args.v0, ROOT)}/`, `{os.path.relpath(args.v1, ROOT)}/` (logged CMG-RRT queries, T = 30 s). "
         "Generated by `scripts/analysis_v1.py`. Nothing here is simulated.\n"]
    st0, st1 = stats(v0), stats(v1)
    c1 = Counter(r["status"] for r in s1.values())
    L.append("## Label counts\n")
    L.append(f"- v1: **{st1['queries']} queries**, {len(set((r['assembly_id'], r['state_key']) for r in v1))} states, "
             f"{len(set(r['assembly_id'] for r in v1))} assemblies with labels; summaries: {dict(c1)}")
    skip1 = Counter(r.get("reason", "").split(" ")[0] for r in s1.values() if r["status"] == "skipped")
    L.append(f"- v1 skip reasons: {dict(skip1)}")
    L.append(f"- v0 (run 01): {st0['queries']} queries, summaries: {dict(Counter(r['status'] for r in s0.values()))}\n")

    L.append("## All labels: v0 vs v1\n")
    L.append("| metric | v0 learned | v1 exact |\n|---|---|---|")
    for k in ["queries", "success_rate", "unsolved", "unsolved_start_invalid", "start_invalid_share_of_unsolved",
              "start_valid_rate_all", "errors", "success_time_p10_p50_p90", "success_iter_p50_p90_max",
              "planner_s_total", "prep_s_p50_p90", "setup_time_s_p50_p90"]:
        f = lambda v: f"{v:.3f}" if isinstance(v, float) else str(v)
        L.append(f"| {k} | {f(st0[k])} | {f(st1[k])} |")

    # ---- paired: assembled state (depth 0) of assemblies labelled in both
    d0 = {(r["assembly_id"], r["part_id"]): r for r in v0 if r["depth"] == 0}
    d1 = {(r["assembly_id"], r["part_id"]): r for r in v1 if r["depth"] == 0}
    keys = sorted(set(d0) & set(d1))
    shared = sorted(set(a for a, _ in keys))
    L.append(f"\n## Paired comparison on the assembled state (depth 0), {len(shared)} assemblies labelled in both, "
             f"{len(keys)} (assembly, part) queries\n")
    if keys:
        p0, p1 = stats([d0[k] for k in keys]), stats([d1[k] for k in keys])
        L.append("| metric | v0 learned | v1 exact |\n|---|---|---|")
        for k in ["success_rate", "unsolved", "unsolved_start_invalid", "start_invalid_share_of_unsolved",
                  "start_valid_rate_all", "success_time_p10_p50_p90", "planner_s_total"]:
            f = lambda v: f"{v:.3f}" if isinstance(v, float) else str(v)
            L.append(f"| {k} | {f(p0[k])} | {f(p1[k])} |")
        ct = Counter((d0[k]["outcome"], d1[k]["outcome"]) for k in keys)
        L.append("\nOutcome crosstab (v0 → v1): " + ", ".join(f"{a}→{b}: {n}" for (a, b), n in sorted(ct.items())))
        uv = [k for k in keys if d0[k]["outcome"] != "success" and d1[k]["outcome"] == "success"]
        L.append(f"\nOf the {sum(1 for k in keys if d0[k]['outcome'] != 'success')} v0-unsolved queries, {len(uv)} succeed in v1; "
                 f"{sum(1 for k in uv if d0[k].get('start_valid') is False)} of those had an invalid v0 start (SDF artifact).")
        both_t = [(d0[k]["time_s"], d1[k]["time_s"]) for k in keys if d0[k]["outcome"] == d1[k]["outcome"] == "success"]
        if both_t:
            r = np.array([b / max(a, 1e-9) for a, b in both_t])
            L.append(f"\nQueries that succeed in both ({len(both_t)}): planner time v1/v0 per query median "
                     f"{np.median(r):.2f} (p10 {np.percentile(r, 10):.2f}, p90 {np.percentile(r, 90):.2f}); "
                     f"v0 median {np.median([a for a, _ in both_t]):.2f} s, v1 median {np.median([b for _, b in both_t]):.2f} s.")
    # ---- assembly status change
    sh = sorted(set(s0) & set(s1))
    trans = Counter((s0[a]["status"], s1[a]["status"]) for a in sh)
    L.append(f"\n## Assembly status, v0 → v1 ({len(sh)} assemblies with a summary in both)\n")
    L.append(", ".join(f"{a}→{b}: {n}" for (a, b), n in sorted(trans.items())))
    sc = sorted(a for a in sh if s0[a]["status"] == "stuck" and s1[a]["status"] == "complete")
    L.append(f"\nStuck in v0 and complete in v1: **{len(sc)}** ({', '.join(sc[:40])}{' ...' if len(sc) > 40 else ''})")
    cs = sorted(a for a in sh if s0[a]["status"] == "complete" and s1[a]["status"] == "stuck")
    L.append(f"\nComplete in v0 and stuck in v1: **{len(cs)}** ({', '.join(cs[:40])})")

    # ---- rotation
    rs = [r for r in v1 if r["outcome"] == "success" and (r.get("path_max_rot_deg") or 0) > args.rot_deg]
    L.append(f"\n## Rotation in v1 successful paths (max rotation > {args.rot_deg:.0f}°)\n")
    L.append(f"{len(rs)} of {st1['success']} successful queries, {len(set((r['assembly_id'], r['state_key']) for r in rs))} states, "
             f"{len(set(r['assembly_id'] for r in rs))} assemblies. Caveat: CMG-RRT paths can rotate when a translation would "
             "also work, so this is rotation *in the logged path*, not rotation that was *needed*.")
    nrot1 = [r for r in v1 if r["outcome"] == "success" and r["iterations"] > 1]
    L.append(f"\nSuccessful v1 queries needing more than 1 RRT iteration: {len(nrot1)} "
             f"({len(set(r['assembly_id'] for r in nrot1))} assemblies).")

    # ---- throughput from the labelling log
    try:
        lines = [l for l in open(args.label_log) if "total_q=" in l]
        if lines:
            last = lines[-1]
            mins = float(last.split("]")[0].strip("[ ").split()[0])
            nq = int(last.split("total_q=")[1].split()[0])
            L.append(f"\n## Labelling throughput\n\nLast progress line of `{os.path.relpath(args.label_log, ROOT)}`: "
                     f"{nq} queries in {mins:.1f} min = **{nq / (mins / 60):.0f} queries/hour** (10 workers, this session; "
                     "includes restarts' first state only from the restart time).")
    except Exception as e:  # noqa: BLE001
        L.append(f"\n(throughput parse failed: {e})")

    # ---- figures
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
        fig, ax = plt.subplots(1, 2, figsize=(10, 3.8))
        for labs, name, c in ((v0, "v0 learned", "#DD8452"), (v1, "v1 exact", "#4C72B0")):
            t = np.sort([max(r["time_s"], 1e-2) for r in labs if r["outcome"] == "success"])
            if len(t):
                ax[0].plot(t, np.arange(1, len(t) + 1) / len(t), label=f"{name} (n={len(t)})", color=c)
            sm = np.array([r["start_min_sdf"] for r in labs if r.get("start_min_sdf") is not None])
            ax[1].hist(np.clip(sm, -0.05, 0.05), bins=60, alpha=0.6, label=name, color=c, density=True)
        ax[0].set_xscale("log"); ax[0].set_xlabel("planner seconds (successful queries)"); ax[0].set_ylabel("CDF")
        ax[0].legend(frameon=False, fontsize=8); ax[0].set_title("Planner time of successes")
        ax[1].axvline(-0.005, color="k", lw=0.8, ls="--"); ax[1].set_xlabel("start min SDF (clipped to ±0.05)")
        ax[1].set_title("Start clearance (dashed: −ε)"); ax[1].legend(frameon=False, fontsize=8)
        for a_ in ax:
            a_.spines[["top", "right"]].set_visible(False)
        fig.tight_layout()
        fp = os.path.join(args.fig_dir, "v0_vs_v1.png")
        fig.savefig(fp, dpi=130)
        L.append(f"\n![v0 vs v1]({os.path.relpath(fp, os.path.dirname(args.out))})")
    except Exception as e:  # noqa: BLE001
        L.append(f"\n(plot failed: {e})")

    # ---- replay on v1 (planner only, and with prep + setup)
    L.append("\n## Per-state replay on v1\n")
    for extra, name in (([], "replay_pilot_v1.md"), (["--with-prep"], "replay_pilot_v1_with_prep.md")):
        out_md = os.path.join(os.path.dirname(args.out), name)
        cmd = [sys.executable, os.path.join(ROOT, "scripts/replay_pilot.py"), "--labels",
               os.path.join(args.v1, "labels.jsonl"), "--out-md", out_md, "--fig-dir", args.fig_dir, "--title",
               "pilot_v1" + (" (planner + prep + setup)" if extra else " (planner only)"), "--fig-name",
               "replay_pilot_v1", "--out-json", out_md.replace(".md", "_states.jsonl")] + extra
        p = subprocess.run(cmd, capture_output=True, text=True, cwd=ROOT)
        L.append(f"- `{os.path.relpath(out_md, ROOT)}` (exit {p.returncode}){': ' + p.stderr[-400:] if p.returncode else ''}")
    L.append("\nKey replay tables are reproduced in REPORT.md; the full tables are in the two files above.")
    json.dump({"v0": st0, "v1": st1, "v1_status": dict(c1)}, open(args.out.replace(".md", ".json"), "w"), indent=1)
    open(args.out, "w").write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
